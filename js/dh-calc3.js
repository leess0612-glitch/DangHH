/* ══════════════════════════════════════════════════════════════════════
   요금 셈하는 공용 부품 (세 번째 판) · dh-calc3.js

   목록 화면과 상세 화면이 같은 값을 내도록 셈하는 곳을 하나로 모았습니다.
   두 번째 판(dh-rental2.js)에서 확인된 규칙을 그대로 옮겼습니다.

   ★ 반값도 타사보상 추가할인도 「그 약정을 골랐을 때 붙는 프로모션」입니다.
     약정마다 개월 수와 금액이 다릅니다.
   ⚠ 브랜드마다 「프모」 칸의 뜻이 다릅니다
       SK  : 프모가 이미 반값이 적용된 요금 → 또 깎으면 안 됩니다
       쿠쿠 : 프모가 그냥 그 줄의 월 요금   → 반값은 따로 깎아야 합니다
     그래서 「기본의 60% 이하인가」를 재서 가릅니다.
   ══════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';

  function 돈(n) { return Number(n).toLocaleString('ko-KR'); }
  function 반내림(n) { return Math.round(n / 2 / 10) * 10; }
  function 만원(n) {
    if (n % 10000 === 0) return (n / 10000) + '만원';
    if (n % 1000 === 0) return (n / 1000) + '천원';
    return 돈(n) + '원';
  }
  function 짧게(v) {
    var s = String(v).replace(/\s*약정$/, '');
    var m = /^(방문|셀프|관리없음)\s*\(?\s*(\d+)\s*개월/.exec(s);
    if (m) return m[1] + ' ' + m[2] + '개월';
    /* 코웨이는 「4M(4개월점검주기)」처럼 적습니다 — 「4개월 점검」으로 줄입니다 */
    var c = /^\d+M\s*\(\s*(\d+)\s*개월/.exec(s);
    if (c) return c[1] + '개월 점검';
    if (/^관리없음/.test(s)) return '관리 없음';
    return s;
  }

  /* 한 칸(약정+관리)의 값을 셈합니다 */
  function 셈(p, 약정, 관리, 타사켬) {
    var 칸 = (p.요금 || {})[약정 + '|' + 관리];
    if (!칸) return null;
    var 기본 = 칸.기본 != null ? 칸.기본 : (칸.프모 != null ? 칸.프모 : 칸.타사);
    if (기본 == null) return null;

    var 값 = 기본, 취소 = null, 말 = [], 뒤값 = null;
    var 더 = (p.타사더 || {})[약정] || null;

    var 칸반값 = null;
    if (칸.프모글) {
      var mm = /(\d+)\s*(?:개월|M)\s*반값/.exec(칸.프모글);
      if (mm) 칸반값 = +mm[1];
    }
    /* 반값은 브랜드를 가리지 않고 모두 적용합니다 (2026-09-09 사장님 지시).
       찾는 차례
         ① 그 칸이 직접 「6개월 반값」이라고 적어 두었으면 그것
         ② 아니면 제품에 딸린 약정별 반값표
       ⚠ 다만 ②는 **그 칸에 다른 프로모션이 적혀 있지 않을 때만** 씁니다.
         반값표는 관리 방식을 구분하지 않아서, 교원웰스처럼
         「셀프는 반값·방문은 3개월 면제」인 제품에 잘못 붙을 수 있습니다.
         LG 만은 반값이 다른 할인 위에 겹치는 것이 정책이라 늘 씁니다. */
    var 반값개월 = 칸반값 ||
                   ((p.코드 === 'lg' || !칸.프모글) ? (p.반값 || {})[약정] : null) || null;
    var 이미반값 = 칸반값 != null && 칸.프모 != null && 칸.기본 != null &&
                   칸.프모 <= 칸.기본 * 0.6;

    /* 1. 다른 할인(전용모델·특가·H규정 등)을 먼저 씌웁니다.
       ⚠ SK 는 「프모」가 이미 반값이 적용된 값이라 여기서 씌우면 두 번 깎입니다.
         그래서 「이미반값」인 칸만 건너뜁니다(3번에서 프모를 그대로 씁니다). */
    if (칸.프모 != null && !이미반값 && 칸.프모 < 값) { 값 = 칸.프모; 취소 = 기본; }

    /* 2. 타사보상 — 이달 할인이 더 쌀 때는 값이 올라가지 않게 그대로 둡니다 */
    if (타사켬 && 칸.타사 != null) {
      var 타사값 = 칸.타사;
      if (더) 타사값 = Math.max(0, 타사값 - 더.돈);
      if (타사값 < 값) {
        말.push('타사보상 적용가입니다. 쓰던 정수기 증빙이 필요합니다.');
        if (더) {
          뒤값 = 칸.타사;
          말.unshift('처음 <b>' + 더.개월 + '개월</b> 요금입니다. 이후 <b>' + 돈(뒤값) + '원</b>');
        }
        값 = 타사값; 취소 = 기본;
      } else {
        말.push('이 약정은 <b>이달 할인</b>이 타사보상보다 유리해 그대로 두었습니다.');
      }
    }

    /* 3. 반값 — LG 는 위 결과에 겹치고, 다른 브랜드는 타사보상과 택1 */
    var 반값쓸까 = 반값개월 && (p.코드 === 'lg' || !타사켬);
    if (반값쓸까) {
      뒤값 = 값;
      값 = (이미반값 && !타사켬) ? 칸.프모 : 반내림(값);
      /* 반값이 늘 첫 달부터인 것은 아닙니다.
         현대큐밍 딜라이트 2 는 「4~6회차」처럼 중간에 시작합니다(엑셀 프로모션 칸).
         그런 제품만 `반값때:{약정:'4~6회차'}` 를 자료에 적어 둡니다. */
      var 때 = (p.반값때 || {})[약정];
      말.unshift(때 ? ('<b>' + 때 + '</b>에 해당하는 <b>' + 반값개월 +
                       '개월</b>만 반값입니다. 그 밖 기간은 <b>' + 돈(뒤값) + '원</b>')
                    : ('처음 <b>' + 반값개월 + '개월</b> 요금입니다. 이후 <b>' + 돈(뒤값) + '원</b>'));
      취소 = 취소 || 기본;
    } else if (!타사켬 && 칸.프모 != null && 칸반값 == null && 칸.프모 < 기본 && 칸.프모글) {
      말.unshift(칸.프모글 + ' 들어간 값입니다');
    }

    var 기간 = (p.총기간 || {})[약정];
    if (기간) 말.push(기간);

    var 딱글 = null;
    if (반값쓸까) 딱글 = 반값개월 + '개월 반값';
    else if (타사켬 && 값 !== 기본 && 칸.타사 != null && 값 <= 칸.타사) {
      딱글 = 더 ? ('타사보상 + ' + 더.개월 + '개월 ' + 만원(더.돈)) : '타사보상';
    } else if (칸.프모 != null && 값 === 칸.프모 && 칸.프모글) 딱글 = 짧게(칸.프모글);

    var 카 = (window.제휴카드자료 || {})[p.코드];
    return {
      값: 값, 기본: 기본, 딱글: 딱글,
      카드: 카 ? Math.max(0, 값 - 카.깎을돈) : null,
      취소: (취소 != null && 취소 !== 값) ? 취소 : null,
      말: 말.join(' · ')
    };
  }

  /* 목록에 쓸 「가장 싼 조합」 — 계산기가 없으므로 대표 값 하나를 고릅니다.

     ★ 2026-09-09 고침 (사장님 지시)
       ① 늘 **신규(타사보상 없음)** 로만 셈합니다. 타사보상은 상세 화면 계산기에서
         손님이 직접 고르는 것이라, 목록에 섞이면 무슨 값인지 헷갈립니다.
       ② 정상가·프로모션가·제휴카드가·딱지를 **한 조합에서 통째로** 가져옵니다.
         예전에는 정상가와 프로모션가를 따로 골라서, 서로 다른 약정의 값이
         한 줄에 나란히 적히는 일이 있었습니다. */
  function 가장싼값(p) {
    var 고른 = null;
    Object.keys(p.요금 || {}).forEach(function (k) {
      var 약정 = k.split('|')[0], 관리 = k.split('|')[1];
      var 결 = 셈(p, 약정, 관리, false);
      if (!결) return;
      if (고른 === null || 결.값 < 고른.값) { 고른 = 결; 고른.약정 = 약정; 고른.관리 = 관리; }
    });
    if (!고른) return null;
    return {
      기본: 고른.기본, 프모: 고른.값, 카드: 고른.카드,
      딱글: 고른.딱글, 약정: 고른.약정, 관리: 고른.관리
    };
  }

  /* 처음 보여 줄 조합 — **목록에 적힌 그 값** 그대로 엽니다.

     ★ 2026-09-10 고침
       예전에는 「정상가가 가장 싼 칸」을 골랐습니다. 그런데 목록은 프로모션까지 친
       「실제로 가장 싼 칸」을 적습니다. 둘이 달라서, 목록에서 10,450원을 보고 누른
       손님이 상세 화면에서 15,900원을 보는 일이 **14종**에서 일어나고 있었습니다.
       (반값이 붙은 칸은 정상가가 더 비싼 경우가 많습니다) */
  function 첫조합(p) {
    var 첫 = { 약정: null, 관리: null };
    var 싼 = 가장싼값(p);
    if (싼) { 첫.약정 = 싼.약정; 첫.관리 = 싼.관리; }
    if (첫.약정 === null) {
      var 제일 = null;
      Object.keys(p.요금 || {}).forEach(function (k) {
        var v = p.요금[k].기본;
        if (v == null) return;
        if (제일 === null || v < 제일) {
          제일 = v; 첫.약정 = k.split('|')[0]; 첫.관리 = k.split('|')[1];
        }
      });
    }
    if (첫.약정 === null) {
      var 열 = p.열 || [], 관 = p.관리 || [];
      첫.약정 = 열[열.length - 1] || null;
      첫.관리 = 관[0] || null;
    }
    return 첫;
  }

  /* 상세 화면 주소 — 「브랜드-모델」을 소문자 영문으로 씁니다.

     ⛔⛔ 2026-09-10 전면 교체 — 예전에는 모델명을 그대로 써서 한글 방 이름이 생겼습니다.
       **깃허브 페이지는 한글 폴더 주소를 못 찾습니다**(`/카톡/index.html`=200 인데
       `/카톡/`=404). 그대로 올렸으면 목록에서 제품을 누를 때 201장이 전부 404였습니다.

     경쟁사도 모두 영문입니다 (2026-09-10 실제로 눌러 확인)
       아정당 /electronics/overview/4020/detail/51697   ← 숫자 번호
       인잘알 /product/86-coway-chp-7220n              ← 번호+브랜드+모델
       미소   /rental/water_purifier/CHP-7220N          ← 모델 그대로
     우리는 인잘알처럼 「브랜드-모델」로 갑니다 — 사람이 읽을 수 있고 브랜드도 드러납니다.

     ⚠ 모델명이 한글이거나(현대큐밍 「딜라이트 아이」) 서로 겹치는 제품은
       자료에 `주소:'qming-delight-i'` 처럼 **직접 적어 둡니다**. 그것이 있으면 그대로 씁니다. */
  function 슬러그(s) {
    return String(s == null ? '' : s).toLowerCase()
      .replace(/[()[\]]/g, '')                 /* 괄호는 지웁니다 — 주소에서 지저분합니다 */
      .replace(/[^a-z0-9]+/g, '-')             /* 남은 글자·기호는 붙임표 하나로 */
      .replace(/^-+|-+$/g, '');
  }
  function 방이름(모델) { return 슬러그(모델); }

  /* ⚠ `p.코드`(브랜드)는 목록·상세 부품이 화면을 그릴 때 붙여 줍니다.
     껍데기를 만드는 프로그램은 그 부품을 돌리지 않아 비어 있습니다.
     주소가 화면과 껍데기에서 달라지면 링크가 어긋나므로, 없으면 여기서 찾습니다. */
  function 브랜드코드(p) {
    if (p.코드) return p.코드;
    var 답 = '';
    (window.브랜드모음 || []).forEach(function (자) {
      if ((자.제품 || []).indexOf(p) >= 0) 답 = 자.코드 || '';
    });
    return 답;
  }
  function 제품주소(p) {
    if (p.주소) return p.주소;
    var 방 = 슬러그(브랜드코드(p) + '-' + p.모델);
    var 겹 = 0;
    (window.브랜드모음 || []).forEach(function (자) {
      (자.제품 || []).forEach(function (x) {
        if (!x.주소 && 슬러그((x.코드 || 자.코드 || '') + '-' + x.모델) === 방) 겹++;
      });
    });
    if (겹 > 1 && p.사진) 방 += '-' + 슬러그(String(p.사진).split('-').pop());
    return 방;
  }

  /* 프로모션 딱지 색 — 뜻이 같은 것끼리 한 색입니다 (당현함 디자인보드 5절).
       반값 계열      → half (파랑 채움)
       요금할인·면제  → off  (남색 채움)
       특가·한정      → deal (빨강 채움)
       그 밖          → etc  (회색 바탕 + 회색 글씨)
     ⚠ 색을 새로 지어내지 말 것. 이 네 갈래 안에서만 씁니다. */
  function 딱지갈래(글) {
    var s = String(글 || '');
    if (/반값/.test(s)) return 'half';
    if (/면제|할인|원|%/.test(s)) return 'off';
    if (/특가|한정|최저|균일|프로모션/.test(s)) return 'deal';
    return 'etc';
  }

  window.요금셈 = { 셈: 셈, 가장싼값: 가장싼값, 첫조합: 첫조합,
                    제품주소: 제품주소, 방이름: 방이름, 슬러그: 슬러그, 딱지갈래: 딱지갈래,
                    돈: 돈, 짧게: 짧게, 만원: 만원 };
})();
