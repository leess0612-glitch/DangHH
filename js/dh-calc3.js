  function 슬러그(s) {
    return String(s == null ? '' : s).toLowerCase()
      .replace(/[()[\]]/g, '')                 /* 괄호는 지웁니다 — 주소에서 지저분합니다 */
      .replace(/[^a-z0-9]+/g, '-')             /* 남은 글자·기호는 붙임표 하나로 */
      .replace(/^-+|-+$/g, '');
  }
