  /* ⚠ `p.코드`(브랜드)는 목록·상세 부품이 화면을 그릴 때 붙여 줍니다.
     껍데기를 만드는 프로그램은 그 부품을 돌리지 않아 비어 있습니다.
     주소가 화면과 껍데기에서 달라지면 링크가 어긋나므로, 없으면 여기서 찾습니다. */
  function 브랜드코드(p) {
    if (p.코드) return p.코드;
    var 답 = '';
    (window.브랜드모음 || []).forEach(function (자) {
      if ((자.제품 || []).indexOf(p) >= 0) 답 = 자.코드 || '';
    });
    return 답;
  }
